// utils/questionPolicy.js
// Replaces hasQuestionChanged. Pure functions, no DB access, easy to unit test.

const CHOICE_TYPES = new Set(['single_choice', 'multi_choice']);
const TEXT_TYPES = new Set(['short_text', 'long_text']);
const RANGE_TYPES = new Set(['rating', 'number']);

// "Cosmetic" label edits (case, punctuation, whitespace) are NOT breaking.
// Anything else is, because we can't tell a typo fix from a changed meaning.
const normalizeLabel = (s = '') =>
    String(s)
        .normalize('NFKC')
        .toLowerCase()
        .replace(/[^\p{L}\p{N}]+/gu, ' ')
        .trim();

const strictenedMin = (o, n) => n !== undefined && (o === undefined || n > o);
const strictenedMax = (o, n) => n !== undefined && (o === undefined || n < o);

/**
 * True if old answers would no longer mean the same thing under the new
 * definition, so the question must be versioned (archive old, mint new id).
 * `old` is the stored subdoc; `incoming` is the client payload.
 */
function hasBreakingChange(old, incoming) {
    const o = old.config ?? {};
    const n = incoming.config ?? {};

    if (old.type !== incoming.type) return true;
    if (normalizeLabel(old.label) !== normalizeLabel(incoming.label))
        return true;

    if (CHOICE_TYPES.has(old.type)) {
        const next = new Map(
            (n.options ?? [])
                .filter((x) => x.optionId)
                .map((x) => [x.optionId, x])
        );
        for (const opt of o.options ?? []) {
            const kept = next.get(opt.optionId);
            if (!kept) return true; // option removed
            if (normalizeLabel(kept.label) !== normalizeLabel(opt.label))
                return true; // relabeled
        }
        // appended options (no optionId / unknown id) are non-breaking
    }

    if (old.type === 'rating') {
        // 4 on a 1-5 scale != 4 on a 1-10 scale, so ANY scale change is breaking
        if (o.min !== n.min || o.max !== n.max) return true;
    }
    if (old.type === 'number') {
        // widening is safe, narrowing could invalidate stored answers
        if (strictenedMin(o.min, n.min) || strictenedMax(o.max, n.max))
            return true;
    }
    if (TEXT_TYPES.has(old.type)) {
        if (strictenedMax(o.maxLength, n.maxLength)) return true;
    }

    return false;
}

/**
 * Whitelist config fields per type. Option IDs are kept ONLY if they belong
 * to `validOptIds` (the stored question's options); otherwise fresh ones are
 * generated by the schema default.
 */
function buildConfig(type, config, validOptIds = null) {
    if (!config) return undefined;
    const out = {};

    if (RANGE_TYPES.has(type)) {
        if (config.min !== undefined) out.min = config.min;
        if (config.max !== undefined) out.max = config.max;
    }
    if (TEXT_TYPES.has(type) && config.maxLength !== undefined) {
        out.maxLength = config.maxLength;
    }
    if (CHOICE_TYPES.has(type) && Array.isArray(config.options)) {
        out.options = config.options.map((opt) => ({
            ...(validOptIds && opt.optionId && validOptIds.has(opt.optionId)
                ? { optionId: opt.optionId }
                : {}),
            label: opt.label
        }));
    }
    return Object.keys(out).length ? out : undefined;
}

/**
 * Trusted-fields-only copy of a client question. Never copies questionId,
 * archived, archivedAt, or rootQuestionId from the client.
 * Pass `old` for in-place edits so existing optionIds survive.
 */
function pickQuestion(q, order, old = null) {
    const validOptIds = old
        ? new Set((old.config?.options ?? []).map((o) => o.optionId))
        : null;
    return {
        type: q.type,
        label: q.label,
        required: Boolean(q.required),
        order,
        config: buildConfig(q.type, q.config, validOptIds)
    };
}

// ---------- schema-level validation ----------

const isInt = Number.isInteger;

/** Call once after defining QuestionSchema (add rootQuestionId + archived default there too). */
function attachQuestionValidation(QuestionSchema) {
    QuestionSchema.pre('validate', function () {
        const { type, config = {} } = this;
        const bad = (path, msg) => this.invalidate(path, msg);

        if (CHOICE_TYPES.has(type)) {
            const opts = config.options ?? [];
            if (opts.length < 2)
                bad(
                    'config.options',
                    'choice questions need at least 2 options'
                );
            const labels = opts.map((o) => normalizeLabel(o.label));
            if (new Set(labels).size !== labels.length)
                bad('config.options', 'option labels must be unique');
            const ids = opts.map((o) => o.optionId);
            if (new Set(ids).size !== ids.length)
                bad('config.options', 'duplicate optionId');
        } else if (config.options?.length) {
            bad('config.options', `${type} questions cannot have options`);
        }

        if (type === 'rating') {
            if (!isInt(config.min) || !isInt(config.max))
                bad('config', 'rating needs integer min and max');
            else if (config.min >= config.max)
                bad('config', 'rating min must be < max');
        } else if (type === 'number') {
            if (
                config.min !== undefined &&
                config.max !== undefined &&
                config.min > config.max
            )
                bad('config', 'min must be <= max');
        } else if (config.min !== undefined || config.max !== undefined) {
            bad('config', `${type} questions cannot have min/max`);
        }

        if (TEXT_TYPES.has(type)) {
            if (
                config.maxLength !== undefined &&
                (!isInt(config.maxLength) || config.maxLength < 1)
            )
                bad('config.maxLength', 'maxLength must be a positive integer');
        } else if (config.maxLength !== undefined) {
            bad('config.maxLength', `${type} questions cannot have maxLength`);
        }
    });
}

/** Array-level validator for FormSchema.questions. */
const questionsArrayValidator = {
    validator(questions) {
        const ids = questions.map((q) => q.questionId);
        if (new Set(ids).size !== ids.length) return false;
        return questions.some((q) => !q.archived); // at least one active question
    },
    message: 'questions must have unique ids and at least one active question'
};

module.exports = {
    hasBreakingChange,
    buildConfig,
    pickQuestion,
    normalizeLabel,
    attachQuestionValidation,
    questionsArrayValidator
};

